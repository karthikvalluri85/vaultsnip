/**
 * On-device layout builder (Phase 2, beta): a masked screenshot in, a replica spec out, with no AI key and no network.
 *
 *   panels  (panels.ts)  where each visual sits, from an edge map and recursive cuts
 *   reading (charts.ts)  each panel's type and mark sizes, from pixel geometry and word layout
 *   tables  (tables.ts)  table, grouped-table and pivot structure, and report parameters, from word positions
 *   here                 rows, spans, heights, titles and theme, in the spec the replica engine already reads
 *
 * Privacy: the input is the masked image plus OCR word boxes. Masked words have their text removed here, before any
 * step runs, so the only text that can reach the spec is text that is readable in the masked image anyway. Every value
 * in the replica is still generated by the engine from 0-100 shapes; nothing here reads a number.
 */
import { area, height, medianHeight, toRgb, width, wordsIn, type Box, type Img, type Word } from './image';
import { findPanels, type Panel } from './panels';
import { looksLikeTable, readPanel, splitTitle, formatOf, type ChartType } from './charts';
import { readTable, tableVisual } from './tables';
import { panelConfidence, pageConfidence, swallowedVisuals, CONFIDENCE_THRESHOLD } from './confidence';

export interface BuildInput {
  image: Img;
  words: Word[];
  /** The mask boxes drawn on the image (visible as grey boxes): masked numbers that OCR did not return as words. */
  masks?: { x: number; y: number; w: number; h: number }[];
}
export interface PanelReport {
  box: Box; type: string; certainty: number; title: string; features: Record<string, number>;
  /** 0-1: estimated probability that this panel is a real visual of this type (src/layout/confidence.ts). */
  confidence: number;
  /** The id of the visual it became in the spec, when it became one. */
  vid?: string;
}
export interface BuildResult {
  spec: Record<string, unknown> & { rows: { height: string; visuals: Record<string, unknown>[] }[] };
  panels: PanelReport[];
  /** Share of the page's content (words and marks) that lies inside a detected panel, 0-1. */
  coverage: number;
  ms: number;
  /** 0-1: estimated share of the replica that matches the original (src/layout/confidence.ts). */
  confidence: number;
}

const MAX_VISUALS = 20;

/** Only position survives for a masked word. Applied to every input, whatever the caller sent. */
export function sanitize(words: Word[]): Word[] {
  return (words || []).filter((w) => w && Number.isFinite(w.x) && Number.isFinite(w.y) && w.w > 0 && w.h > 0)
    .map((w) => ({ x: w.x, y: w.y, w: w.w, h: w.h, kept: !!w.kept, text: w.kept ? String(w.text || '').trim() : '' }));
}

/**
 * Mask boxes that hold no OCR word become masked words (position only), so a KPI whose number OCR missed still has
 * its big number. Boxes over several words are left out: the words already describe them.
 */
export function withMasks(words: Word[], masks: BuildInput['masks']): Word[] {
  const ms = (masks || []).filter((m) => m && m.w > 0 && m.h > 0);
  const overlap = (w: { x: number; y: number; w: number; h: number }, m: typeof w) => {
    const ox = Math.min(w.x + w.w, m.x + m.w) - Math.max(w.x, m.x), oy = Math.min(w.y + w.h, m.y + m.h) - Math.max(w.y, m.y);
    return ox > 0 && oy > 0 && ox * oy > Math.min(w.w * w.h, m.w * m.h) * 0.3;
  };
  // a masked word is seen as the grey box drawn over it (the box, not the hidden glyphs, is what the image shows)
  const seen = words.map((w) => {
    if (w.kept) return w;
    const m = ms.find((m) => overlap(w, m) && m.w * m.h < w.w * w.h * 6);
    return m ? { ...w, x: Math.min(w.x, m.x), y: Math.min(w.y, m.y), w: Math.max(w.x + w.w, m.x + m.w) - Math.min(w.x, m.x), h: Math.max(w.y + w.h, m.y + m.h) - Math.min(w.y, m.y) } : w;
  });
  const extra = ms.filter((m) => !words.some((w) => overlap(w, m))).map((m) => ({ x: m.x, y: m.y, w: m.w, h: m.h, kept: false, text: '' }));
  return seen.concat(extra);
}

/** A title from the top line of small words; covered words become one [Client]. */
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length);
export function titleOf(ws: Word[], b: Box, med: number) {
  const small = ws.filter((w) => w.h <= med * 1.9);
  if (!small.length) return { text: '', words: [] as Word[] };
  const top = Math.min(...small.map((w) => w.y));
  // the title line: words whose middle is on it (a reader's box can be drawn taller than its word, as for a short "By"
  // between two longer words; a KPI's big value is far taller and stays out)
  const mid = mean(small.filter((w) => Math.abs(w.y - top) < med * 0.8).map((w) => w.y + w.h / 2));
  const line = ws.filter((w) => w.h <= med * 2.6 && Math.abs(w.y + w.h / 2 - mid) < med * 0.8 && w.y < b[1] + height(b) * 0.35).sort((a, c) => a.x - c.x);
  const band: Word[] = [];
  for (const w of line) { const last = band[band.length - 1]; if (last && w.x - (last.x + last.w) > med * 2.5) break; band.push(w); }
  if (!band.some((w) => w.kept && w.text)) return { text: '', words: band };
  const text = band.map((w) => (w.kept && w.text ? w.text : '[Client]')).join(' ').replace(/(\[Client\]\s*)+/g, '[Client] ').trim();
  return { text, words: band };
}

export function buildSpec(input: BuildInput): BuildResult {
  const t0 = Date.now();
  const img = toRgb(input.image), W = img.width, H = img.height;
  const ocrWords = sanitize(input.words);
  const med = medianHeight(ocrWords);
  const words = withMasks(ocrWords, input.masks);
  // panels from what the image shows, without the tall blocks the app draws over a column of numbers (they distort them);
  // each panel is then read with the mask-aware words, where a masked value is its grey box
  const panels = findPanels(img, words.filter((w) => w.kept || w.h <= med * 3.5), med, ocrWords);
  const pageBox: Box = [0, 0, W, H];

  // the page title: large visible words above every panel, or a full-width text strip at the top
  const firstY = panels.length ? Math.min(...panels.map((p) => p.b[1])) : H;
  let pageSubtitle = '', headingBottom = 0;
  let pageTitle = titleOf(words.filter((w) => w.y + w.h <= firstY + 2), pageBox, med * 3).text;
  const readings = panels.map((p) => {
    const t = titleOf(p.words, p.b, med);
    const features: Record<string, number> = {};
    const r = readPanel(img, p.b, wordsIn(words, p.b), med, t.text, features, p.words);
    return { p, r, title: t.text, titleWords: t.words, features };
  });

  // a paginated report: no charts, and the page's words form one grid (read from the OCR boxes, since the app merges
  // masks over a column of numbers into one tall block)
  const CHARTS = ['column', 'bar', 'line', 'area', 'pie', 'donut', 'scatter', 'treemap'];
  // (a page of separate KPI tiles lines its words up in a grid too, but a report never holds two KPI tiles)
  // (a best-guess chart, drawn where no reader could type a panel, is no evidence against a report)
  const report = !readings.some((x) => CHARTS.includes(x.r.type) && !x.r.guess) && readings.filter((x) => x.r.type === 'kpi').length < 2
    && looksLikeTable(ocrWords, med) ? readTable(ocrWords, pageBox) : null;
  if (report && report.columns.length >= 2) {
    const top = Math.min(...ocrWords.map((w) => w.y));
    const title = report.title || pageTitle || titleOf(ocrWords.filter((w) => w.y - top < med * 1.2), pageBox, med * 2).text;
    const visual: Record<string, unknown> = { id: 'v1', span: 12, title: title || '', ...tableVisual(report, title) };
    return {
      spec: { title: title || 'Report', subtitle: '', parameters: report.parameters, filters: [], rows: [{ height: 'l', visuals: [visual] }] },
      panels: [{ box: pageBox, type: String(visual.type), certainty: 0.7, title, features: { columns: report.columns.length, headerLevels: report.headerLevels, dataRows: report.dataRows }, confidence: 0.7, vid: 'v1' }],
      coverage: 1, confidence: 0.7, ms: Date.now() - t0,
    };
  }
  // a header band: text-only pieces at the very top (a title bar, possibly in large type) are the page title, not
  // visuals; a group set far to the right (a date range) is the subtitle
  // (but a row of KPI cards across the top is not a title: two or more KPI tiles side by side, each with a big value)
  // marks <= 2 excludes real charts; KPI panels up to marks=12 are also included (navigation bars render as KPI panels
  // with many UI-element marks; the tiles guard below still protects two-or-more real KPI tiles at the top).
  // Text/placeholder panels get a slightly taller band (0.13) to catch full-width filter bars that sit just above 0.12.
  const inBand = (x: (typeof readings)[number]) => {
    const limit = (x.r.type === 'text' || x.r.type === 'placeholder') ? H * 0.13 : H * 0.12;
    return x.p.b[3] <= limit && (x.features.marks <= 2 || (x.r.type === 'kpi' && x.features.marks <= 12));
  };
  const tiles = readings.filter((x) => inBand(x) && x.r.type === 'kpi' && x.features.bigMasked >= 1);
  const topBand = readings.filter((x) => inBand(x) && (x.r.type === 'kpi' || x.r.type === 'text' || x.r.type === 'placeholder') && !(tiles.length >= 2 && tiles.includes(x)));
  if (topBand.length && topBand.length < readings.length) {
    const ws = topBand.flatMap((x) => x.p.words).sort((a, b) => a.x - b.x);
    const groups: Word[][] = [];
    for (const w of ws) { const g = groups[groups.length - 1], last = g && g[g.length - 1]; if (last && w.x - (last.x + last.w) < W * 0.15) g.push(w); else groups.push([w]); }
    const show = (list: Word[]) => list.map((w) => (w.kept && w.text ? w.text : '[Client]')).join(' ').replace(/(\[Client\]\s*)+/g, '[Client] ').replace(/\s*\|\s*/g, ' | ').trim();
    if (ws.some((w) => w.kept && w.text)) {
      pageTitle = show(groups[0]); pageSubtitle = groups.slice(1).map(show).join(' · ');
      topBand.forEach((t) => { headingBottom = Math.max(headingBottom, t.p.b[3]); readings.splice(readings.indexOf(t), 1); });
    }
  }
  // the page heading: a short text strip above every other panel (or a wide strip at the very top)
  const others = (r: (typeof readings)[number]) => readings.filter((o) => o !== r);
  const head = readings.find((x) => (x.r.type === 'text' || x.r.type === 'placeholder') && height(x.p.b) < H * 0.12 && x.p.words.length <= 10
    && (others(x).every((o) => o.p.b[1] >= x.p.b[3] - 2) || (x.p.b[1] <= firstY + 2 && width(x.p.b) > W * 0.5)));
  if (head) { if (!pageTitle) pageTitle = head.title; headingBottom = Math.max(headingBottom, head.p.b[3]); readings.splice(readings.indexOf(head), 1); }

  // second look, with the readings in hand: a chart cut into pieces (bars far apart, nothing framing them) is re-read as
  // one panel, and a title strip sitting right above a chart becomes its title
  const CHARTISH = ['column', 'bar', 'line', 'area', 'placeholder'];
  const reread = (b: Box) => {
    const t = titleOf(wordsIn(words, b), b, med), features: Record<string, number> = {};
    const r = readPanel(img, b, wordsIn(words, b), med, t.text, features, wordsIn(ocrWords, b));
    return { p: { b, words: wordsIn(words, b), med }, r, title: t.text, titleWords: t.words, features };
  };
  const union = (a: Box, b: Box): Box => [Math.min(a[0], b[0]), Math.min(a[1], b[1]), Math.max(a[2], b[2]), Math.max(a[3], b[3])];
  for (let changed = true, guard = 0; changed && guard < 40; guard++) {
    changed = false;
    for (const a of readings) {
      const piece = readings.find((b) => b !== a && !b.title && CHARTISH.includes(b.r.type) && CHARTISH.includes(a.r.type) && !b.r.guess && !a.r.guess && b.features.marks > 0
        && Math.abs(a.p.b[3] - b.p.b[3]) <= Math.max(6, med) && Math.max(a.p.b[0], b.p.b[0]) - Math.min(a.p.b[2], b.p.b[2]) <= Math.max(med * 4, W * 0.03));
      if (!piece) continue;
      const m = reread(union(a.p.b, piece.p.b));
      if (m.r.type !== 'column' && m.r.type !== 'bar' && m.r.type !== a.r.type) continue;
      readings.splice(readings.indexOf(a), 1, m); readings.splice(readings.indexOf(piece), 1); changed = true; break;
    }
  }
  for (const s of [...readings]) {
    // (a title strip is short: a tall card above a chart is a visual of its own)
    if (!(s.r.type === 'placeholder' || s.r.type === 'text') || s.features.marks > 1 || s.p.words.length > 8 || !s.title
      || height(s.p.b) > Math.max(med * 6, H * 0.08)) continue;
    const below = readings.find((c) => c !== s && CHARTISH.concat(['pie', 'donut', 'scatter', 'treemap', 'table']).includes(c.r.type) && c.r.type !== 'placeholder'
      && c.p.b[1] >= s.p.b[3] - 2 && c.p.b[1] - s.p.b[3] < Math.max(med * 6, H * 0.06)
      && Math.min(c.p.b[2], s.p.b[2]) - Math.max(c.p.b[0], s.p.b[0]) > Math.min(width(s.p.b), width(c.p.b)) * 0.5);
    if (!below) continue;
    const m = reread(union(below.p.b, s.p.b));
    readings.splice(readings.indexOf(below), 1, m.r.type === below.r.type ? m : { ...below, title: below.title || s.title });
    readings.splice(readings.indexOf(s), 1);
  }

  foldSubFigures(readings, W, H, med, words);

  // Page furniture, not visuals: a filter or slicer row, a breadcrumb, a tab strip, a legend standing on its own, a
  // note or callout over the picture. Each is words on the page with nothing drawn — no chart marks, no table rules,
  // next to no ink — while every real visual either draws something or is a KPI card, which is a value or two, a
  // label, and little else. (Drawing them loses nothing of the original and spares the user cards it never had.)
  // (a line chart is a stroke and little else: a sparse line over a wide card inks barely any of it, so a panel
  //  holding a thin stroke is a chart however little of the card it covers)
  // (a table is words on a grid, and the grid is drawn: words laid out in columns with no rule, no stripe and no ink
  //  at all are a legend or a list of filter values, which is furniture like the rest)
  // (only a narrow one: a real table runs across its card, and plenty are drawn without a single rule)
  const bareTable = (x: (typeof readings)[number]) => x.r.type === 'table' && !x.features.marks && !x.features.coverage
    && width(x.p.b) < W * 0.25;
  // (a line of six or more words running together is a sentence: a note, a footer, a commentary box. A filter list or
  //  a legend sets one or two words to a line.)
  const prose = (x: (typeof readings)[number]) => {
    const rows = new Map<number, number>();
    for (const w of x.p.words) { const k = Math.round((w.y + w.h / 2) / Math.max(1, med)); rows.set(k, (rows.get(k) || 0) + 1); }
    return [...rows.values()].some((n) => n >= 6);
  };
  const furniture = (x: (typeof readings)[number]) => !prose(x) && (x.features.marks <= 1 && x.features.coverage < 0.025
    && !x.features.grid && !(x.features.thin && (x.features.vivid || x.features.swatches))
    && !(x.r.type === 'kpi' && x.features.bigMasked <= 4)) || bareTable(x);
  // A narrow strip running down one side of the page is the tool's rail — navigation, a filter pane, a slicer list —
  // not a visual. No dashboard puts a chart in a sixth of the width over a third of the height against the margin.
  const rail = (x: (typeof readings)[number]) => (x.p.b[0] <= W * 0.03 || x.p.b[2] >= W * 0.97)
    && width(x.p.b) <= W * 0.16 && height(x.p.b) >= H * 0.3;
  // A KPI card is a card: a value with a label, in a block. Over 4.5 times as wide as it is tall, or taller than it is
  // wide by half, it is a caption, a legend or a note that happened to hold a masked word — not a card. (Of 86
  // hand-labelled KPI cards on real dashboards every one lies between 0.88 and 4.33 times as wide as tall; a 0.17
  // buffer above that gives the 4.5 upper bound, safely below the 4.79 nearest false positive in the benchmark set.)
  const oddKpi = (x: (typeof readings)[number]) => {
    if (x.r.type !== 'kpi') return false;
    const a = width(x.p.b) / Math.max(1, height(x.p.b));
    return a > 4.5 || a < 0.6;
  };
  // A chart panel under 130 px tall is page furniture — a legend strip, a footer note, or a top navigation bar.
  // Across all 27 benchmark dashboards every legitimately-matched chart is ≥ 153 px tall; the 23 px gap gives
  // safe margin even for generated panels that underestimate the truth bounding box by 15–20 %.
  const thinChart = (x: (typeof readings)[number]) => height(x.p.b) < 130
    && ['column', 'bar', 'line', 'area', 'combo', 'scatter', 'pie', 'donut', 'treemap'].includes(x.r.type);
  // A text or placeholder panel that spans nearly the full page width is a section-divider strip or a banner,
  // not a chart or a data card. The widest real text visual across all 27 benchmark dashboards is under 71 % of page
  // width; any panel ≥ 90 % wide and at least 8× wider than tall is page furniture.
  const wideTextStrip = (x: (typeof readings)[number]) => (x.r.type === 'text' || x.r.type === 'placeholder')
    && width(x.p.b) >= W * 0.90 && width(x.p.b) > height(x.p.b) * 8;
  // A chart panel that starts within the top 5 % of the page and ends before the 22 % mark, with at most 2 marks,
  // is part of the application's header chrome — a banner graphic, a logo area, or a decorative sparkline in the
  // title bar — not a data visual. Real charts never start that high with so little drawn ink.
  const topEdgeChart = (x: (typeof readings)[number]) => {
    const CHART_TYPES = ['area', 'line', 'column', 'bar', 'scatter', 'pie', 'donut', 'treemap', 'combo'];
    return CHART_TYPES.includes(x.r.type) && x.p.b[1] <= H * 0.05 && x.p.b[3] <= H * 0.22 && x.features.marks <= 2;
  };
  // A panel whose bottom clips into the last 1.5 % of the page and draws fewer than 6 marks is a footer element —
  // a page number, a thin navigation strip, or a table that ran off the screenshot edge. Real visuals at the
  // page bottom always draw more marks (across 27 benchmark dashboards the minimum for a correct bottom-edge panel
  // is 8 marks; the nearest false positive sits at 5 marks with a 3-mark gap).
  const bottomFooter = (x: (typeof readings)[number]) => x.p.b[3] > H * 0.985
    && x.features.marks < 6 && height(x.p.b) < H * 0.5;
  // A KPI in the side band (left or right 22 % of the page) that has no rectangular primitives, draws at most
  // 8 marks, and contains more than 14 OCR words is reading navigation chrome or the dashboard header instead
  // of a data tile. Real side-band KPI tiles have at most 12 words across all 27 benchmark dashboards; the
  // nearest false positive sits at 18, a 5-word gap that makes the threshold of 14 safe.
  const sideWordyKpi = (x: (typeof readings)[number]) => x.r.type === 'kpi'
    && (x.p.b[2] <= W * 0.22 || x.p.b[0] >= W * 0.78)
    && !x.features.rects && x.features.marks <= 8 && (x.features.words ?? 0) > 14;
  // A KPI whose bottom edge lies within the top 20 % of the page and is over 3.5× wider than tall is a
  // sub-header label, a column heading, or a title band misidentified as a KPI. Real top-row KPI cards across
  // all 27 benchmark dashboards have aspects under 3.0 (max = 2.94); the threshold of 3.5 gives a 0.56-unit
  // buffer above that maximum.
  const topWideKpi = (x: (typeof readings)[number]) => x.r.type === 'kpi'
    && x.p.b[3] <= H * 0.20 && width(x.p.b) > height(x.p.b) * 3.5;
  // A KPI narrower than 10 % of page width but taller than 13 % of page height is a column separator or a
  // side-panel fragment misidentified as a KPI. Real narrow KPI tiles (< 10 %W) are short labels — the tallest
  // correct one across 27 benchmark dashboards is 7.2 %H; the shortest false positive is 14.1 %H, a 6.9-point
  // gap that makes the threshold of 13 %H safe.
  const narrowKpi = (x: (typeof readings)[number]) => x.r.type === 'kpi'
    && width(x.p.b) < W * 0.10 && height(x.p.b) > H * 0.13;
  // An area chart that starts above the 12 % mark of the page is a coloured-background tile or a header
  // decoration — not a data visual. Real area charts begin below the top chrome. Verified across 27 benchmark
  // dashboards: 0 correct area panels start before 12 % of page height.
  const topEdgeArea = (x: (typeof readings)[number]) => x.r.type === 'area' && x.p.b[1] < H * 0.12;
  // A line chart that reaches the lower 12 % of the page (b3 > 88 %H) carrying more than 20 marks is a fragment
  // produced by a horizontal cut through a larger visual — not a standalone chart. Every correct line that reaches
  // the lower 12 % across the 27 benchmark dashboards has at most 10 marks; the phantom sits at 51, a 41-mark gap
  // that makes the threshold of 20 safe.
  const heavyBottomLine = (x: (typeof readings)[number]) => x.r.type === 'line'
    && x.p.b[3] > H * 0.88 && x.features.marks > 20;
  // A real data visual needs enough space to communicate something. A placeholder panel that fits in less than
  // 8 % of page width AND 8 % of page height is a stray gap in the segmentation — a narrow strip between two
  // larger panels — not a data visual. Verified across 27 benchmark dashboards: 0 correct panels caught.
  const smallPlaceholder = (x: (typeof readings)[number]) => x.r.type === 'placeholder'
    && width(x.p.b) < W * 0.08 && height(x.p.b) < H * 0.08;
  // A KPI card is a single value — a masking box and perhaps a label. Any panel whose type resolved to KPI but
  // carries 15 or more rectangle primitives is a UI widget: a navigation row, a filter bar, a chip group. Across
  // 27 benchmark dashboards every correct KPI tile has at most 12 rectangles (from Superstore2026Dark); the nearest
  // false positive sits at 19, a 6-unit gap that makes the threshold of 15 safe.
  const busyKpi = (x: (typeof readings)[number]) => x.r.type === 'kpi' && (x.features.rects ?? 0) >= 15;
  // The same rail, cut into boxes: three or more panels stacked against one margin, none of them drawing much, running
  // down most of the page between them. That is a filter pane or a navigation column, whatever the cutter made of it.
  const side = (x: (typeof readings)[number], left: boolean) => (left ? x.p.b[2] <= W * 0.22 : x.p.b[0] >= W * 0.78)
    && x.features.marks <= 8 && !x.features.rects && x.features.coverage < 0.12;
  const stack = [true, false].map((left) => readings.filter((x) => side(x, left)))
    .find((g) => g.length >= 3 && Math.max(...g.map((x) => x.p.b[3])) - Math.min(...g.map((x) => x.p.b[1])) >= H * 0.4) || [];
  // A band across the very top of the picture, five times wider than it is tall: the dashboard's own title bar, or the
  // tool's. A visual that shape is rare; one in that place is rarer still.
  const header = (x: (typeof readings)[number]) => x.p.b[1] <= H * 0.03 && width(x.p.b) >= W * 0.85
    && width(x.p.b) > height(x.p.b) * 5;
  const real = readings.filter((x) => !furniture(x) && !rail(x) && !oddKpi(x) && !topWideKpi(x) && !narrowKpi(x) && !sideWordyKpi(x) && !thinChart(x) && !wideTextStrip(x) && !topEdgeChart(x) && !topEdgeArea(x) && !heavyBottomLine(x) && !bottomFooter(x) && !smallPlaceholder(x) && !busyKpi(x) && !header(x) && !stack.includes(x));
  if (real.length) readings.splice(0, readings.length, ...real);
  // keep the largest visuals when there are too many; then rows by vertical overlap, left to right
  const kept = readings.length > MAX_VISUALS ? [...readings].sort((a, b) => area(b.p.b) - area(a.p.b)).slice(0, MAX_VISUALS) : readings;
  const ordered = [...kept].sort((a, b) => a.p.b[1] - b.p.b[1] || a.p.b[0] - b.p.b[0]);
  const rows: (typeof ordered)[] = [];
  for (const x of ordered) {
    const row = rows.find((r) => r.some((o) => { const ov = Math.min(o.p.b[3], x.p.b[3]) - Math.max(o.p.b[1], x.p.b[1]); return ov > Math.min(height(o.p.b), height(x.p.b)) * 0.4; }));
    if (row) row.push(x); else rows.push([x]);
  }
  let n = 0;
  const specRows = rows.map((row) => {
    row.sort((a, b) => a.p.b[0] - b.p.b[0]);
    const total = row.reduce((s, x) => s + width(x.p.b), 0);
    const spans = row.map((x) => Math.max(row.length > 6 ? 1 : 2, Math.round((width(x.p.b) / total) * 12)));
    if (row.length <= 6) { let d = 12 - spans.reduce((a, b) => a + b, 0); while (d !== 0) { const i = spans.indexOf(d > 0 ? Math.min(...spans) : Math.max(...spans)); spans[i] += d > 0 ? 1 : -1; d += d > 0 ? -1 : 1; } }
    const hRatio = Math.max(...row.map((x) => height(x.p.b))) / W;
    const kpis = row.every((x) => x.r.type === 'kpi');
    const h = kpis || hRatio < 0.11 ? 's' : hRatio > 0.3 ? 'l' : 'm';
    return {
      height: h,
      visuals: row.map((x, i) => {
        const id = 'v' + ++n;
        (x as { vid?: string }).vid = id;
        if (x.r.type === 'table') {
          const tw = wordsIn(ocrWords, x.p.b).filter((w) => !x.titleWords.some((t) => t.x === w.x && t.y === w.y));
          const t = readTable(tw, x.p.b);
          if (t && t.columns.length >= 2) return { id, span: spans[i], title: x.title, ...tableVisual(t, x.title) };
          return { id, span: spans[i], type: 'text', title: x.title, content: '' };
        }
        const type: ChartType | 'bubble' = x.r.type === 'scatter' && (x.r.fields as { bubble?: boolean }).bubble ? 'bubble' : x.r.type;
        const fields = { ...x.r.fields }; delete (fields as { bubble?: boolean }).bubble;
        if (type === 'kpi') return { id, span: spans[i], type, title: '', ...fields };
        if (type === 'text') {
          const body = x.p.words.filter((w) => w.kept && w.text && !x.titleWords.includes(w)).map((w) => w.text).join(' ');
          return body ? { id, span: spans[i], type, title: x.title, content: body } : { id, span: spans[i], type, title: '', content: x.title };
        }
        return { id, span: spans[i], type, title: x.title, ...fields };
      }),
    };
  });

  // theme: the most common mark colours
  const colors = new Map<string, number>();
  readings.forEach((x) => { if (x.r.color) colors.set(x.r.color, (colors.get(x.r.color) || 0) + area(x.p.b)); });
  const theme = [...colors.entries()].sort((a, b) => b[1] - a[1]).map(([c]) => c);
  const title = pageTitle || (readings.length ? '' : 'Dashboard');

  // coverage: words and panels; content outside every panel is content the replica will miss
  const inPanel = (w: Word) => readings.some((x) => w.x + w.w / 2 >= x.p.b[0] && w.x + w.w / 2 <= x.p.b[2] && w.y + w.h / 2 >= x.p.b[1] && w.y + w.h / 2 <= x.p.b[3]);
  // (below the page heading, which is the title, not a visual the replica misses)
  const below = words.filter((w) => w.y > Math.max(firstY, headingBottom) - 2);
  const coverage = below.length ? below.filter(inPanel).length / below.length : readings.length ? 1 : 0;

  const reports: PanelReport[] = readings.map((x) => {
    const signals = { type: x.r.type, certainty: x.r.certainty, area: area(x.p.b) / (W * H), titled: !!x.title, features: x.features };
    return { box: x.p.b.map(Math.round) as Box, type: x.r.type, certainty: Math.round(x.r.certainty * 100) / 100, title: x.title, features: x.features,
      confidence: Math.round(panelConfidence(signals) * 100) / 100, vid: (x as { vid?: string }).vid };
  });
  const coverageR = Math.round(coverage * 100) / 100;

  return {
    spec: { title, subtitle: pageSubtitle, ...(theme.length ? { theme: { primary: theme[0], secondary: theme[1] || theme[0] } } : {}), filters: [], rows: specRows.filter((r) => r.visuals.length) },
    panels: reports,
    coverage: coverageR,
    confidence: Math.round(pageConfidence(reports.filter((r) => r.vid).map((r) => r.confidence), coverageR,
      swallowedVisuals(reports.map((r) => area(r.box) / (W * H)), reports.map((r) => r.type))) * 100) / 100,
    ms: Date.now() - t0,
  };
}

/**
 * A sub-figure of a KPI card ("Current workforce: 6,009" under the card's big value, a "vs LY" delta) is part of that
 * card, not a visual of its own: a tiny KPI or placeholder panel with no chart in it joins a panel at least three times
 * its size that holds it, or that it sits right above or below with most of its width over it. Changes `readings`.
 */
export function foldSubFigures<T extends { p: { b: Box; words: Word[] }; r: { type: string }; features: Record<string, number> }>(
  readings: T[], W: number, H: number, med: number, words: Word[]): void {
  const union = (a: Box, b: Box): Box => [Math.min(a[0], b[0]), Math.min(a[1], b[1]), Math.max(a[2], b[2]), Math.max(a[3], b[3])];
  for (const f of [...readings]) {
    if (!(f.r.type === 'kpi' || f.r.type === 'placeholder') || (f.features.marks || 0) > 1 || f.p.words.length > 10 || area(f.p.b) > W * H * 0.008) continue;
    const [cx, cy] = [(f.p.b[0] + f.p.b[2]) / 2, (f.p.b[1] + f.p.b[3]) / 2];
    const over = (h: Box) => Math.min(h[2], f.p.b[2]) - Math.max(h[0], f.p.b[0]);
    const host = readings.filter((h) => h !== f && area(h.p.b) >= area(f.p.b) * 3 && (
      (cx >= h.p.b[0] && cx <= h.p.b[2] && cy >= h.p.b[1] && cy <= h.p.b[3])
      || (over(h.p.b) >= width(f.p.b) * 0.6 && Math.min(Math.abs(f.p.b[1] - h.p.b[3]), Math.abs(h.p.b[1] - f.p.b[3])) <= Math.max(med * 3, H * 0.02))))
      .sort((a, b) => area(a.p.b) - area(b.p.b))[0];
    if (!host) continue;
    const u = union(host.p.b, f.p.b);
    host.p = { ...host.p, b: u, words: wordsIn(words, u) };
    readings.splice(readings.indexOf(f), 1);
  }
}

